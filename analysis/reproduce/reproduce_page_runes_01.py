# ------------------------------------------------------------------ scorer
class Quadgram(object):
    """English-likeness by quadgram log10-probability. Higher = more English."""

    def __init__(self):
        self.d = {}
        total = 0
        with open(os.path.join(LPDATA, "english_quadgrams.txt"), encoding="ascii") as f:
            for line in f:
                q, c = line.split()
                c = int(c)
                self.d[q] = c
                total += c
        lt = math.log10(total)
        for q in self.d:
            self.d[q] = math.log10(self.d[q]) - lt
        self.floor = math.log10(0.01) - lt

    def score(self, text):
        t = re.sub(r"[^A-Z]", "", text.upper())
        if len(t) < 4:
            return -999.0
        return sum(self.d.get(t[i:i + 4], self.floor) for i in range(len(t) - 3))

    def score_norm(self, text):
        t = re.sub(r"[^A-Z]", "", text.upper())
        n = len(t) - 3
        return self.score(t) / n if n > 0 else -999.0


# ------------------------------------------------------------------ ciphers
def atbash(idxs):
    return [(N - 1) - c for c in idxs]


def shift(idxs, k, sign=-1):
    return [(c + sign * k) % N for c in idxs]


def repeat_key(key_indices, length):
    return [key_indices[i % len(key_indices)] for i in range(length)]


def decrypt_with_interrupters(runes, stream, scorer, sign=-1, beam_width=500):
    """Beam search over which F runes are nulls, for ANY keystream.

    Rule (as confirmed by the solved pages): only the F rune is ever a null,
    not every F is, a null F is dropped from the plaintext and does NOT advance
    the keystream. The beam keeps the `beam_width` best-scoring skip/keep
    prefixes at every F, so it scales past 2**n brute force.
    """
    beams = [(frozenset(), 0, [])]
    f_seen = 0
    for ch in runes:
        c0 = RUNE_TO_IDX[ch]
        if ch == INTERRUPTER:
            nxt = []
            for iset, j, dec in beams:
                nxt.append((iset | {f_seen}, j, dec))                       # null
                nxt.append((iset, j + 1, dec + [IDX_TO_TRANS[(c0 + sign * stream[j]) % N]]))
            f_seen += 1
            nxt.sort(key=lambda b: scorer.score("".join(b[2])), reverse=True)
            beams = nxt[:beam_width]
        else:
            beams = [(iset, j + 1, dec + [IDX_TO_TRANS[(c0 + sign * stream[j]) % N]])
                     for iset, j, dec in beams]
    beams.sort(key=lambda b: scorer.score("".join(b[2])), reverse=True)
    iset, _j, dec = beams[0]
    return "".join(dec), sorted(iset)


def sieve_primes(count):
    primes, cand = [], 2
    while len(primes) < count:
        if all(cand % p for p in primes if p * p <= cand):
            primes.append(cand)
        cand += 1
    return primes


def canon(s):
    """Collapse the alphabet's genuine ambiguities before word matching:
    C=K, U=V, S=Z, Q=C. The runic alphabet cannot distinguish these."""
    s = re.sub(r"[^A-Z]", "", s.upper())
    for a, b in (("K", "C"), ("V", "U"), ("Z", "S"), ("Q", "C")):
        s = s.replace(a, b)
    return s


