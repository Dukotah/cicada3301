N = 29
RUNE_TO_IDX = {r: i for (i, r, _t, _p) in GEMATRIA}
IDX_TO_TRANS = {i: t for (i, _r, t, _p) in GEMATRIA}
INTERRUPTER = "\u16a0"  # the F rune
_TRANS_SORTED = sorted(((t, i) for (i, _r, t, _p) in GEMATRIA), key=lambda x: -len(x[0]))


def runes_only(text):
    return "".join(c for c in text if c in RUNE_TO_IDX)


def to_indices(runes):
    return [RUNE_TO_IDX[c] for c in runes]


def to_translit(idxs):
    return "".join(IDX_TO_TRANS[i % N] for i in idxs)


def keyword_to_indices(word):
    """Parse a Latin keyword into Gematria indices, longest transliteration first."""
    s = word.upper().replace(" ", "")
    out, i = [], 0
    while i < len(s):
        for t, idx in _TRANS_SORTED:
            if s.startswith(t, i):
                out.append(idx)
                i += len(t)
                break
        else:
            alias = {"V": 1, "K": 5, "Z": 15, "Q": 5}.get(s[i])
            if alias is None:
                raise ValueError("cannot map %r" % s[i])
            out.append(alias)
            i += 1
    return out


