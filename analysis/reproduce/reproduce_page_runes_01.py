def runes_from_scream314(label):
    """First runic code block under the '## <label>' header of the canonical
    transcription markdown. This is the raw artifact; nothing is retyped."""
    path = os.path.join(LPDATA, "scream314_lp.md")
    lines = open(path, encoding="utf-8").read().splitlines()
    start = None
    for i, ln in enumerate(lines):
        if ln.startswith("## ") and label in ln[3:]:
            start = i
            break
    if start is None:
        raise SystemExit("label %r not found in %s" % (label, path))
    end = len(lines)
    for j in range(start + 1, len(lines)):
        if lines[j].startswith("## "):
            end = j
            break
    blocks, cur = [], []
    for ln in lines[start + 1:end]:
        if ln.startswith("    ") or ln.startswith("\t"):
            cur.append(ln.strip())
        elif ln.strip() == "" and cur:
            cur.append("")
        else:
            if cur:
                blocks.append("\n".join(cur))
                cur = []
    if cur:
        blocks.append("\n".join(cur))
    for b in blocks:
        r = runes_only(b)
        if r:
            return r
    raise SystemExit("no runic block under %r" % label)


