#!/usr/bin/env python3
"""Per-lane coverage from shards.json + results/, written to COVERAGE.md.

    python coverage.py                 # print and rewrite COVERAGE.md
    python coverage.py --no-write      # print only (CI)
    python coverage.py --shards X --results-dir Y

A shard counts as volunteer coverage only if its status is 'done' AND results/<id>.json
exists, names the same range, and its result_sha256 recomputes. (Spot-check verification
happens in CI before merge; this script does not re-score.) 'test' shards never count.
Prior coverage is shown separately and only where PARKED-SWEEPS.md documents it.
"""
import argparse
import json
from pathlib import Path

import _kit as K


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--shards", default=None)
    ap.add_argument("--results-dir", default=None)
    ap.add_argument("--no-write", action="store_true")
    a = ap.parse_args()
    db = K.load_shards(a.shards)
    rdir = Path(a.results_dir) if a.results_dir else K.RESULTS_DIR

    out = ["# Volunteer coverage", "",
           "_Generated by `python coverage.py` from `shards.json` + `results/`. Do not edit by hand._", ""]
    for lid, lane in db["lanes"].items():
        space = lane["space"][1] - lane["space"][0]
        shards = sorted((s for s in db["shards"] if s["lane"] == lid and s["status"] != "test"),
                        key=lambda s: s["from"])
        for x, y in zip(shards, shards[1:]):
            assert x["to"] <= y["from"], "overlapping shards %s / %s" % (x["id"], y["id"])
        counts = {"unclaimed": 0, "claimed": 0, "done": 0}
        vol, ncand, nabove, best, flagged, problems = 0, 0, 0, None, [], []
        for s in shards:
            counts[s["status"]] = counts.get(s["status"], 0) + 1
            if s["status"] != "done":
                continue
            p = rdir / ("%s.json" % s["id"])
            if not p.exists():
                problems.append("%s marked done but %s is missing" % (s["id"], p.name))
                continue
            r = json.loads(p.read_text(encoding="utf-8"))
            if r.get("range") != [s["from"], s["to"]] or K.canonical_sha(r) != r.get("result_sha256"):
                problems.append("%s: result range/sha inconsistent, not counted" % s["id"])
                continue
            vol += r["n_scored"]
            ncand += r["n_candidates"]
            nabove += r["n_above_bar"]
            if r["best"] and (best is None or r["best"][1] > best[1]):
                best = r["best"]
            flagged += [(s["id"], x[0], x[1]) for x in r["above_bar"]]
        prior = lane.get("prior", {}).get("covered_seeds", 0)
        shard_total = sum(s["to"] - s["from"] for s in shards)
        out += ["## Lane %s" % lid, "", lane["title"], "",
                "| | seeds | % of 2^32 |", "|---|---:|---:|",
                "| prior work, Rounds 27-42 (%s, %d claim-bar hits) | %s | %.4f %% |"
                % (lane["prior"]["source"].split("analysis/")[-1], lane["prior"]["n_claim_bar_hits"],
                   "{:,}".format(prior), 100.0 * prior / space),
                "| volunteer shards done | %s | %.4f %% |" % ("{:,}".format(vol), 100.0 * vol / space),
                "| **total** | **%s** | **%.4f %%** |" % ("{:,}".format(prior + vol), 100.0 * (prior + vol) / space),
                "| remaining (volunteer shards not done) | %s | %.4f %% |"
                % ("{:,}".format(shard_total - vol), 100.0 * (shard_total - vol) / space), "",
                "Shards: %d done, %d claimed, %d unclaimed (of %d)." % (counts["done"], counts["claimed"],
                                                                      counts["unclaimed"], len(shards)), "",
                "Volunteer shards so far: %s candidates >= %.1f, %d at/above the claim bar %.6f, best %s."
                % ("{:,}".format(ncand), lane["cand_bar"], nabove, lane["claim_bar"], best), ""]
        if prior:
            out += ["Note: " + lane["prior"]["note"], ""]
        if flagged:
            out += ["**Flagged for oracle (NOT solves; see HUMAN-ORACLE.md):**", ""]
            out += ["- %s seed %d pmax %r" % f for f in flagged]
            out.append("")
        if problems:
            out += ["Problems:", ""] + ["- " + x for x in problems] + [""]
    txt = "\n".join(out)
    print(txt)
    if not a.no_write:
        (K.VOL / "COVERAGE.md").write_text(txt, encoding="utf-8")


if __name__ == "__main__":
    main()
