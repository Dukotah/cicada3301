#!/usr/bin/env python3
"""R34-P1 capsule: build MANIFEST.regen.json (COPY) with the corrected payload as canon_256, verify it, diagnose INTACT-FAILs.
Writes only under manifest_regen/. The real MANIFEST.json is read, never written."""
import os, sys, json, hashlib, re, subprocess, shutil
HERE = os.path.dirname(os.path.abspath(__file__)); LANE = os.path.dirname(HERE)
LP = os.path.abspath(os.path.join(LANE, "..", "..", ".."))
REPO = os.path.dirname(LP)
CAP = os.path.join(LP, "handoff", "capsule")
raw = open(os.path.join(CAP, "MANIFEST.json"), "rb").read()
man = json.loads(raw.decode("utf-8"))
shutil.copyfile(os.path.join(CAP, "MANIFEST.json"), os.path.join(HERE, "MANIFEST.orig.copy.json"))
res = open(os.path.join(LANE, "inputs", "resolved", "canon_256.bin"), "rb").read()
old = open(os.path.join(LANE, "inputs", "canon", "canon_256.bin"), "rb").read()
it = next(i for i in man["items"] if i["id"] == "payload.canon_256")
assert hashlib.sha256(old).hexdigest() == it["sha256"], "staged canon != manifest sha"
sup = json.loads(json.dumps(it))
sup["id"] = "payload.canon_256_superseded"
sup["role"] = "The pre-R19-C1 canonicalisation of the pages 49-51 payload (3 bytes differ from canon_256: idx 45 81->107, 50 21->47, 246 224->198). Kept as a record; superseded by payload.canon_256."
sup["path"] = "liber-primus/analysis/pp49_51/canon_256_superseded.bin"
sup["provenance"] = it["provenance"] + ["renamed from canon_256.bin when payload_resolved.bin was promoted (Round 34 P1 plan)"]
it["role"] = it["role"].replace("Input to the B-05", "Corrected to payload_resolved.bin (R19-C1; Round 33 B1/X1; owner decision 2026-10-29). Input to the B-05")
it["provenance"] = it["provenance"] + ["PROVENANCE: payload_resolved.bin (analysis/round19/C1, == round18/L5-payload) copied to canon_256.bin; R19-C1 resolved the 3 bytes idx 45/50/246; Round 33 B1/X1 and Round 34 P1 re-fed it to every reader; owner's 2026-10-29 decision (Option A); previous bytes kept as canon_256_superseded.bin"]
it["sha256"] = hashlib.sha256(res).hexdigest(); it["sha1"] = hashlib.sha1(res).hexdigest(); it["bytes"] = len(res)
it["notes"] = it["notes"] + " [R34-P1] Bytes at idx 45/50/246 are now the R19-C1 resolved values; the six contested bytes (25,175,182,199,215,237) are unchanged and still contested."
k = man["items"].index(it); man["items"].insert(k + 1, sup)
s = man["summary"]; s["n_items"] += 1; s["by_status"]["in-repo"] += 1; s["hash_verified_locally"] += 1
man["r34_p1_note"] = "COPY regenerated by round34/P1-payload-promotion/manifest_regen/regen.py; generated_utc/generator fields of the original are kept."
json.dump(man, open(os.path.join(HERE, "MANIFEST.regen.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
open(os.path.join(HERE, "MANIFEST.regen.json"), "a").write("\n")
print("canon_256 new sha256", it["sha256"], "superseded sha256", sup["sha256"])

# ---- verifier copies: identical code, MANIFEST/REPO re-pointed, optional path overrides (post-rename simulation)
v = open(os.path.join(CAP, "verify_capsule.py"), encoding="utf-8").read()
def mk(name, manifest, overrides):
    t = v.replace('HERE = os.path.dirname(os.path.abspath(__file__))', 'HERE = r"%s"' % CAP)
    t = t.replace('REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))', 'REPO = r"%s"' % REPO)
    t = t.replace('MANIFEST = os.path.join(HERE, "MANIFEST.json")', 'MANIFEST = r"%s"' % manifest)
    t = t.replace('        ap = os.path.join(REPO, path)', '        ap = OVERRIDES.get(path) or os.path.join(REPO, path)')
    t = t.replace('OK, ABSENT,', 'OVERRIDES = %r\nOK, ABSENT,' % overrides, 1)
    open(os.path.join(HERE, name), "w", encoding="utf-8").write(t)
    return name
post = {"liber-primus/analysis/pp49_51/canon_256.bin": os.path.join(LANE, "inputs", "resolved", "canon_256.bin"),
        "liber-primus/analysis/pp49_51/canon_256_superseded.bin": os.path.join(LANE, "inputs", "canon", "canon_256.bin")}
runs = [("verify_A_orig_manifest.py", os.path.join(CAP, "MANIFEST.json"), {}, "verify_A_orig_manifest.log", "A: ORIGINAL manifest, real tree (baseline: the 13 pre-existing INTACT-FAIL)"),
        ("verify_B_regen_prerename.py", os.path.join(HERE, "MANIFEST.regen.json"), {}, "verify_B_regen_prerename.log", "B: REGEN copy, real tree, no rename yet (canon_256 expected to FAIL; superseded ABSENT)"),
        ("verify_C_regen_postrename_sim.py", os.path.join(HERE, "MANIFEST.regen.json"), post, "verify_C_regen_postrename_sim.log", "C: REGEN copy with canon_256/superseded paths mapped to staged files = post-rename simulation")]
for name, man_p, ov, log, label in runs:
    mk(name, man_p, ov)
    r = subprocess.run([sys.executable, os.path.join(HERE, name), "--json", os.path.join(HERE, log.replace(".log", ".json"))], capture_output=True, text=True, cwd=HERE)
    open(os.path.join(HERE, log), "w", encoding="utf-8").write("# " + label + "\n# exit code %d\n" % r.returncode + r.stdout + r.stderr)
    tail = [l for l in r.stdout.splitlines() if re.match(r"\s+(OK|ABSENT|INTACT-FAIL|DRIFT|DEAD|SKIP)\s*:", l)]
    print(label, "->", r.returncode, tail)

# ---- CRLF diagnosis of the INTACT-FAILs of run A
rep = json.load(open(os.path.join(HERE, "verify_A_orig_manifest.json")))
mf = json.load(open(os.path.join(CAP, "MANIFEST.json"), encoding="utf-8"))
byid = {i["id"]: i for i in mf["items"]}
diag = []
for row in rep["rows"]:
    if row["result"] != "INTACT-FAIL": continue
    i = byid[row["id"]]; p = os.path.join(REPO, i["path"]); b = open(p, "rb").read()
    lf = b.replace(b"\r\n", b"\n")
    crlf = b.count(b"\r\n")
    rec = {"id": row["id"], "path": i["path"], "bytes_disk": len(b), "bytes_manifest": i.get("bytes"), "crlf_count": crlf, "lone_cr": lf.count(b"\r"),
           "sha_match_raw": hashlib.sha256(b).hexdigest() == i["sha256"], "sha_match_after_CRLF_to_LF": hashlib.sha256(lf).hexdigest() == i["sha256"],
           "bytes_after_LF": len(lf), "LF_len_equals_manifest_bytes": len(lf) == i.get("bytes")}
    if not rec["sha_match_after_CRLF_to_LF"]:
        # try the reverse: manifest hashed CRLF text? or other normalisation
        rec["sha_match_if_manifest_was_CRLF"] = hashlib.sha256(lf.replace(b"\n", b"\r\n")).hexdigest() == i["sha256"]
        rec["sha_match_after_strip_bom"] = hashlib.sha256(lf.lstrip(b"\xef\xbb\xbf")).hexdigest() == i["sha256"]
    diag.append(rec)
json.dump(diag, open(os.path.join(HERE, "crlf_diagnosis.json"), "w"), indent=1)
for d in diag: print(d["id"], "CRLF=%d" % d["crlf_count"], "LF-sha-match=%s" % d["sha_match_after_CRLF_to_LF"], "len-match=%s" % d["LF_len_equals_manifest_bytes"], {k: v for k, v in d.items() if k.startswith("sha_match_if") or k.startswith("sha_match_after_strip")})
