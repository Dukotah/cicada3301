static void init_tables(void) {
    for (int i = 0; i < NRUNE; i++) {
        TL[i]  = (uint8_t)strlen(TRANS[i]);
        TC0[i] = (uint8_t)(TRANS[i][0] - 'A');
        TC1[i] = (uint8_t)(TL[i] > 1 ? TRANS[i][1] - 'A' : 0);
    }
    for (int x = -29; x <= 57; x++) M29[x + 29] = (uint8_t)(((x % 29) + 29) % 29);
}

/* ------------------------------------------------------------------ model loading */
static void die(const char *msg) { fprintf(stderr, "FATAL: %s\n", msg); exit(1); }

static void load_quadgrams(void) {
    FILE *f = fopen(G_QGRAM_PATH, "r");
    if (!f) die("cannot open quadgram file (QGRAM_PATH in engine.dat)");
    /* pass 1+2 in one go: store counts, then log-normalise (lp/score.py order) */
    static int32_t idxs[90000]; static long cnts[90000];
    int n = 0; long total = 0;
    char q[16]; long c;
    while (fscanf(f, "%15s %ld", q, &c) == 2) {
        if (strlen(q) != 4) die("bad quadgram line");
        int idx = 0;
        for (int i = 0; i < 4; i++) {
            if (q[i] < 'A' || q[i] > 'Z') die("non A-Z quadgram");
            idx = idx * 26 + (q[i] - 'A');
        }
        if (n >= 90000) die("too many quadgram entries");
        idxs[n] = idx; cnts[n] = c; n++; total += c;
    }
    fclose(f);
    if (total != G_QGRAM_TOTAL) die("quadgram total mismatch vs engine.dat");
    double logtotal = log10((double)total);
    double floorv = log10(0.01) - logtotal;
    if (fabs(floorv - G_QGRAM_FLOOR) > 1e-12) die("quadgram floor mismatch vs engine.dat");
    for (int i = 0; i < QSZ; i++) QTAB[i] = floorv;
    for (int i = 0; i < n; i++) QTAB[idxs[i]] = log10((double)cnts[i]) - logtotal;
}

static void load_panel(void) {
    FILE *f = fopen(G_PANEL_PATH, "rb");
    if (!f) die("cannot open panel_lm.f32 (run export_data.py)");
    static float lmf[NREG * NTRI];
    if (fread(lmf, sizeof(float), NREG * NTRI, f) != NREG * NTRI)
        die("panel_lm.f32 short read (expect 9*24389 float32)");
    fclose(f);
    LMT = malloc(sizeof(float) * NTRI * NREG);
    if (!LMT) die("oom");
    for (int t = 0; t < NTRI; t++)
        for (int r = 0; r < NREG; r++)
            LMT[t * NREG + r] = lmf[r * NTRI + t];
}

static void load_engine_dat(const char *path) {
    FILE *f = fopen(path, "r");
    if (!f) die("cannot open engine.dat (run export_data.py first)");
    char key[64];
    char line[8192];
    int nvec_expected = -1;
    if (fscanf(f, "%63s %63s", key, line) != 2 || strcmp(key, "GRIND27DATA"))
        die("bad engine.dat header");
    while (fscanf(f, "%63s", key) == 1) {
        if (!strcmp(key, "PANEL_SHA256")) { if (fscanf(f, "%79s", G_PANEL_SHA) != 1) die("dat"); }
        else if (!strcmp(key, "PANEL_PATH")) { if (fscanf(f, "%1023s", G_PANEL_PATH) != 1) die("dat"); }
        else if (!strcmp(key, "QGRAM_PATH")) { if (fscanf(f, "%1023s", G_QGRAM_PATH) != 1) die("dat"); }
        else if (!strcmp(key, "QGRAM_TOTAL")) { if (fscanf(f, "%ld", &G_QGRAM_TOTAL) != 1) die("dat"); }
        else if (!strcmp(key, "QGRAM_FLOOR")) { if (fscanf(f, "%lf", &G_QGRAM_FLOOR) != 1) die("dat"); }
        else if (!strcmp(key, "QGRAM_NENTRIES")) { long x; if (fscanf(f, "%ld", &x) != 1) die("dat"); }
        else if (!strcmp(key, "NREG")) { int x; if (fscanf(f, "%d", &x) != 1 || x != NREG) die("NREG != 9"); }
        else if (!strcmp(key, "MU")) { for (int i = 0; i < NREG; i++) if (fscanf(f, "%lf", &MU[i]) != 1) die("MU"); }
        else if (!strcmp(key, "SD")) { for (int i = 0; i < NREG; i++) if (fscanf(f, "%lf", &SD[i]) != 1) die("SD"); }
        else if (!strcmp(key, "CAND_BAR")) { if (fscanf(f, "%lf", &G_CAND_BAR) != 1) die("dat"); }
        else if (!strcmp(key, "CLAIM_BAR_PAIR")) { if (fscanf(f, "%lf", &G_CLAIM_PAIR) != 1) die("dat"); }
        else if (!strcmp(key, "CLAIM_BAR_EXACT")) { if (fscanf(f, "%lf", &G_CLAIM_EXACT) != 1) die("dat"); }
        else if (!strcmp(key, "CSCREEN")) {
            int n; if (fscanf(f, "%d", &n) != 1 || n != LSCREEN) die("CSCREEN len");
            for (int i = 0; i < n; i++) if (fscanf(f, "%d", &C_SCREEN[i]) != 1) die("CSCREEN");
        }
        else if (!strcmp(key, "PLANT_SEED")) { if (fscanf(f, "%d", &G_PLANT_SEED) != 1) die("dat"); }
        else if (!strcmp(key, "PLANT_PMAX")) { if (fscanf(f, "%lf", &G_PLANT_PMAX) != 1) die("dat"); }
        else if (!strcmp(key, "PLANT_CIPHER")) {
            int n; if (fscanf(f, "%d", &n) != 1 || n != LSCREEN) die("PLANT_CIPHER len");
            for (int i = 0; i < n; i++) if (fscanf(f, "%d", &G_PLANT_CIPHER[i]) != 1) die("dat");
        }
        else if (!strcmp(key, "PLANT_PLAIN")) {
            int n, v; if (fscanf(f, "%d", &n) != 1 || n != LSCREEN) die("PLANT_PLAIN len");
            for (int i = 0; i < n; i++) { if (fscanf(f, "%d", &v) != 1) die("dat"); G_PLANT_PLAIN[i] = (uint8_t)v; }
        }
        else if (!strcmp(key, "NVEC")) { if (fscanf(f, "%d", &nvec_expected) != 1) die("dat"); }
        else if (!strcmp(key, "VEC")) {
            Vec *v = &G_VEC[G_NVEC];
            unsigned long long s;
            if (fscanf(f, "%llu %lf %lf %d %d %d", &s, &v->pmax, &v->beam_score,
                       &v->ptr_end, &v->n_skips, &v->nchars) != 6) die("VEC");
            v->seed = (uint32_t)s;
            char k2[16]; int x;
            if (fscanf(f, "%15s", k2) != 1 || strcmp(k2, "KS")) die("VEC KS");
            for (int i = 0; i < 128; i++) { if (fscanf(f, "%d", &x) != 1) die("KS"); v->ks128[i] = (uint8_t)x; }
            if (fscanf(f, "%15s", k2) != 1 || strcmp(k2, "PLAIN")) die("VEC PLAIN");
            for (int i = 0; i < LSCREEN; i++) { if (fscanf(f, "%d", &x) != 1) die("PLAIN"); v->plain[i] = (uint8_t)x; }
            G_NVEC++;
        }
        else if (!strcmp(key, "END")) break;
        else die("unknown key in engine.dat");
    }
    fclose(f);
    if (nvec_expected != G_NVEC) die("NVEC mismatch");
}

/* ------------------------------------------------------------------ lane config */
typedef struct {
    char name[32];
    int  pair;         /* 1 = keyskip2 'pair', 0 = keyskip1 'exact' */
    int  max_skip;     /* 8 pair / 3 exact */
    int  reducer;
    int  offset;       /* key offset o */
    uint64_t from, to;
    double cand_bar, claim_bar;
    int  nK;           /* padded keystream length */
} Lane;

static void lane_finish_init(Lane *ln) {
    ln->max_skip = ln->pair ? 8 : 3;
    ln->nK = KS_LEN + LSCREEN * (ln->max_skip + 1) + 8;   /* driftbeam zero-pad, section 3.1 */
    if (ln->cand_bar <= 0) ln->cand_bar = G_CAND_BAR;
    if (ln->claim_bar <= 0) ln->claim_bar = ln->pair ? G_CLAIM_PAIR : G_CLAIM_EXACT;
}

static Lane lane_S1(void) {
    Lane ln; memset(&ln, 0, sizeof ln);
    strcpy(ln.name, "S1");
    ln.pair = 1; ln.reducer = RED_RANDOM29; ln.offset = 0;
    ln.from = 0; ln.to = 4294967296ULL;
    lane_finish_init(&ln);
    return ln;
}

/* per-step tables -- depend only on (cipher, relation), NOT the seed */
typedef struct { uint8_t pm[NRUNE], vm[NRUNE]; } StepTab;

static void build_steps(const int *C, StepTab *st) {   /* sign = -1 throughout */
    for (int i = 1; i < LSCREEN; i++) {
        int ci = C[i];
        int delta = MOD29(ci - C[i-1]);                /* (sign*(C[i-1]-ci)) % 29 with sign=-1 */
        for (int k = 0; k < NRUNE; k++) {
            st[i].pm[k] = MOD29(ci - k);               /* (ci + sign*k) % 29 */
            st[i].vm[k] = MOD29(k - delta);
        }
    }
}

/* ------------------------------------------------------------------ beam decode */
typedef struct {
    double sc;                    /* cum score == quad cum (lam = 0) */
    int32_t acc, nid, nchars;
    uint8_t tail[3], tlen, _pad[3];
} Hyp;

typedef struct {                  /* per-thread scratch */
    MT mt;
    uint8_t Kx[KS_LEN + LSCREEN * 9 + 8 + 8];
    Hyp beams[BEAMW], ch[MAXCH], tmp[MAXCH];
    int16_t par[LSCREEN][MAXCH];
    uint8_t rune[LSCREEN][MAXCH];
    int cnt[NRUNE];
    uint8_t plain[LSCREEN];
} Ctx;

/* stable sort, DESCENDING by sc (Python list.sort(reverse=True) parity).
 * Children arrays are small in practice (avg ~12, max ~128 measured), so a stable
 * insertion sort is the fast path; bottom-up merge covers large n. Both are stable:
 * insertion shifts only on strict <, merge prefers the left run on ties. */
static void stable_sort_desc(Hyp *a, Hyp *t, int n) {
    if (n < 2) return;
    if (n <= 48) {
        for (int i = 1; i < n; i++) {
            if (a[i].sc <= a[i-1].sc) continue;
            Hyp key = a[i];
            int j = i;
            while (j > 0 && a[j-1].sc < key.sc) { a[j] = a[j-1]; j--; }
            a[j] = key;
        }
        return;
    }
    for (int width = 1; width < n; width *= 2) {
        for (int lo = 0; lo < n; lo += 2 * width) {
            int mid = lo + width; if (mid >= n) break;
            int hi2 = lo + 2 * width; if (hi2 > n) hi2 = n;
            int i = lo, j = mid, k = lo;
            while (i < mid && j < hi2)
                t[k++] = (a[i].sc >= a[j].sc) ? a[i++] : a[j++];
            while (i < mid) t[k++] = a[i++];
            while (j < hi2) t[k++] = a[j++];
            memcpy(a + lo, t + lo, sizeof(Hyp) * (size_t)(hi2 - lo));
        }
    }
}

/* Decode `cipher` (120 runes) against ctx->Kx under lane relation; returns final
 * beam-path count artifacts. Mirrors driftbeam.beam_decode exactly (lam=0,
 * max_free=0, start_slack=0, sign=-1). */
typedef struct { double pmax, beam_score; int ptr_end, n_skips, nchars; } DecOut;

static DecOut decode_seed(const Lane *ln, const StepTab *st, const int *cipher, Ctx *cx) {
    const uint8_t *Kx = cx->Kx;
    const int nK = ln->nK, pair = ln->pair, ms = ln->max_skip;
    const int step_pair = pair ? 2 : 1;
    int nb;

    /* init hypothesis (start_slack = 0) */
    {
        int acc0 = ln->offset;
        int p0 = MOD29(cipher[0] - Kx[acc0]);
        Hyp *h = &cx->beams[0];
        h->sc = 0.0; h->acc = acc0; h->nid = 0;
        h->tlen = TL[p0]; h->tail[0] = TC0[p0]; h->tail[1] = TC1[p0];
        h->nchars = TL[p0];
        cx->par[0][0] = -1; cx->rune[0][0] = (uint8_t)p0;
        nb = 1;
    }
    memset(cx->cnt, 0, sizeof cx->cnt);

    for (int i = 1; i < LSCREEN; i++) {
        const uint8_t *pm = st[i].pm, *vm = st[i].vm;
        int nch = 0;
        int16_t *par_row = cx->par[i];
        uint8_t *rune_row = cx->rune[i];
        for (int b = 0; b < nb; b++) {
            const Hyp *h = &cx->beams[b];
            const int base = h->acc + 1;
            int hi = base, maxcnt = 0;
            const int L1 = h->nchars;
            const int long_form = (L1 < 3);
            for (int dsk = 0; dsk <= ms; dsk++) {
                const int acc = base + dsk;
                if (acc >= nK) break;
                int need;
                if (dsk) {
                    if (!pair || (dsk & 1)) {
                        int km = Kx[acc - 1];
                        int c2 = ++cx->cnt[km];
                        if (c2 > maxcnt) maxcnt = c2;
                    }
                    hi = acc;
                    if (pair) {
                        if (dsk & 1) continue;         /* only even advances representable */
                        need = dsk >> 1;
                    } else need = dsk;
                    if (need - maxcnt > 0) break;      /* max_free = 0, monotone prune */
                } else need = 0;
                const int kacc = Kx[acc];
                if (need - cx->cnt[vm[kacc]] > 0) continue;   /* consistency reject */
                const int p = pm[kacc];
                const int la = TL[p];
                double tot;
                uint8_t nt0, nt1, nt2, ntl;
                if (!long_form) {                      /* tlen == 3 guaranteed */
                    const int b3 = (h->tail[0] * 26 + h->tail[1]) * 26 + h->tail[2];
                    if (la == 1) {
                        const int a4 = b3 * 26 + TC0[p];
                        tot = QTAB[a4];
                        nt0 = h->tail[1]; nt1 = h->tail[2]; nt2 = TC0[p]; ntl = 3;
                    } else {
                        const int a4 = b3 * 26 + TC0[p];
                        tot = QTAB[a4] + QTAB[(a4 % 17576) * 26 + TC1[p]];
                        nt0 = h->tail[2]; nt1 = TC0[p]; nt2 = TC1[p]; ntl = 3;
                    }
                } else {                               /* whole translit < 3 chars */
                    uint8_t s2[5]; int n2 = 0;
                    for (int m = 0; m < h->tlen; m++) s2[n2++] = h->tail[m];
                    s2[n2++] = TC0[p];
                    if (la == 2) s2[n2++] = TC1[p];
                    tot = (n2 >= 4)
                        ? QTAB[((s2[0] * 26 + s2[1]) * 26 + s2[2]) * 26 + s2[3]]
                        : 0.0;
                    ntl = (uint8_t)(n2 < 3 ? n2 : 3);
                    nt0 = s2[n2 - ntl]; nt1 = ntl > 1 ? s2[n2 - ntl + 1] : 0;
                    nt2 = ntl > 2 ? s2[n2 - ntl + 2] : 0;
                }
                Hyp *c = &cx->ch[nch];
                c->sc = h->sc + tot;
                c->acc = acc; c->nchars = L1 + la;
                c->tail[0] = nt0; c->tail[1] = nt1; c->tail[2] = nt2; c->tlen = ntl;
                c->nid = nch;
                par_row[nch] = (int16_t)h->nid;
                rune_row[nch] = (uint8_t)p;
                nch++;
            }
            if (hi > base)                             /* histogram reset (touched entries only) */
                for (int m = base; m < hi; m += step_pair) cx->cnt[Kx[m]] = 0;
        }
        stable_sort_desc(cx->ch, cx->tmp, nch);
        nb = nch < BEAMW ? nch : BEAMW;
        memcpy(cx->beams, cx->ch, sizeof(Hyp) * (size_t)nb);
    }

    /* best path + backtrack (beams[0] is max after the stable descending sort) */
    const Hyp *best = &cx->beams[0];
    int node = best->nid;
    for (int step = LSCREEN - 1; step >= 0; step--) {
        cx->plain[step] = cx->rune[step][node];
        node = cx->par[step][node];
    }

    /* panel-max: 118 trigrams, float32 gathers accumulated in double */
    double acc9[NREG] = {0};
    for (int i = 0; i < LSCREEN - 2; i++) {
        const int fidx = (cx->plain[i] * NRUNE + cx->plain[i+1]) * NRUNE + cx->plain[i+2];
        const float *row = LMT + fidx * NREG;
        for (int r = 0; r < NREG; r++) acc9[r] += row[r];
    }
    double pmax = -1e30;
    for (int r = 0; r < NREG; r++) {
        const double z = (acc9[r] / 118.0 - MU[r]) / SD[r];
        if (z > pmax) pmax = z;
    }

    DecOut o;
    o.pmax = pmax;
    o.beam_score = best->nchars > 3 ? best->sc / (double)(best->nchars - 3) : -999.0;
    o.ptr_end = best->acc;
    o.n_skips = best->acc - ln->offset - (LSCREEN - 1);
    o.nchars = best->nchars;
    return o;
}

static DecOut screen_one(const Lane *ln, const StepTab *st, const int *cipher,
                         Ctx *cx, uint32_t w) {
    mt_init_word(&cx->mt, w);
    reduce_stream(&cx->mt, ln->reducer, cx->Kx, KS_LEN);
    memset(cx->Kx + KS_LEN, 0, (size_t)(ln->nK - KS_LEN));
    return decode_seed(ln, st, cipher, cx);
}

/* ------------------------------------------------------------------ self-test (V1 + V2)
 * plant_out (optional): receives the V2 planted-screen DecOut so --mode self-test can
 * emit the contract JSON line without re-running the decode. */
static int self_test(DecOut *plant_out) {
    Lane ln = lane_S1();
    StepTab *st = calloc(LSCREEN, sizeof(StepTab));
    build_steps(C_SCREEN, st);
    Ctx *cx = calloc(1, sizeof(Ctx));
    int fails = 0;
    double worst_pmax = 0, worst_beam = 0;

    for (int v = 0; v < G_NVEC; v++) {
        Vec *V = &G_VEC[v];
        mt_init_word(&cx->mt, V->seed);
        uint8_t ks[128];
        reduce_stream(&cx->mt, RED_RANDOM29, ks, 128);
        if (memcmp(ks, V->ks128, 128)) {
            printf("V1 FAIL seed %u: ks128 mismatch\n", V->seed); fails++; continue;
        }
        DecOut o = screen_one(&ln, st, C_SCREEN, cx, V->seed);
        int pm_ok = memcmp(cx->plain, V->plain, LSCREEN) == 0;
        double dp = fabs(o.pmax - V->pmax), db = fabs(o.beam_score - V->beam_score);
        if (dp > worst_pmax) worst_pmax = dp;
        if (db > worst_beam) worst_beam = db;
        if (!pm_ok || dp > 1e-9 || db > 1e-9 || o.ptr_end != V->ptr_end
            || o.n_skips != V->n_skips || o.nchars != V->nchars) {
            printf("V1 FAIL seed %u: plain_ok=%d dpmax=%.3e dbeam=%.3e ptr %d/%d "
                   "skips %d/%d nchars %d/%d\n", V->seed, pm_ok, dp, db,
                   o.ptr_end, V->ptr_end, o.n_skips, V->n_skips, o.nchars, V->nchars);
            fails++;
        }
    }
    printf("V1 vector parity: %d/%d seeds exact (worst |dpmax| %.3e, worst |dbeam| %.3e) -> %s\n",
           G_NVEC - fails, G_NVEC, worst_pmax, worst_beam, fails ? "FAIL" : "PASS");

    /* V2: planted stage-A screen -- decode the plant cipher with seed 777
       (step tables are cipher-dependent: build them for the plant cipher) */
    StepTab *stp = calloc(LSCREEN, sizeof(StepTab));
    build_steps(G_PLANT_CIPHER, stp);
    DecOut o = screen_one(&ln, stp, G_PLANT_CIPHER, cx, (uint32_t)G_PLANT_SEED);
    free(stp);
    if (plant_out) *plant_out = o;
    int plain_ok = memcmp(cx->plain, G_PLANT_PLAIN, LSCREEN) == 0;
    double dp = fabs(o.pmax - G_PLANT_PMAX);
    int v2ok = plain_ok && dp <= 1e-9 && o.pmax >= ln.cand_bar;
    printf("V2 planted screen: seed %d pmax %.15g (ref %.15g, |d| %.3e) plain_ok=%d "
           ">= cand_bar %.1f: %s -> %s\n", G_PLANT_SEED, o.pmax, G_PLANT_PMAX, dp,
           plain_ok, ln.cand_bar, o.pmax >= ln.cand_bar ? "yes (candidate emitted)" : "NO",
           v2ok ? "PASS" : "FAIL");
    if (!v2ok) fails++;

    free(cx); free(st);
    if (fails) { printf("SELF-TEST: FAIL (%d)\n", fails); return 1; }
    printf("SELF-TEST: PASS -- screen is provably incapable of rejecting the planted "
           "true seed (margin %.2f over bar %.1f). Python (hitfn20) remains the "
           "adjudicator of record on every candidate.\n",
           o.pmax - ln.cand_bar, ln.cand_bar);
    return 0;
}

/* ------------------------------------------------------------------ drill (V3) + bench */
static int drill(void) {
    Lane ln = lane_S1();
    StepTab *st = calloc(LSCREEN, sizeof(StepTab));
    build_steps(C_SCREEN, st);
    Ctx *cx = calloc(1, sizeof(Ctx));
    const uint64_t a = 2149309680ULL, b = 2149309700ULL;
    double best = -1e30; uint64_t bw = 0;
    for (uint64_t w = a; w < b; w++) {
        DecOut o = screen_one(&ln, st, C_SCREEN, cx, (uint32_t)w);
        if (o.pmax >= ln.cand_bar)
            printf("  candidate: seed %llu pmax %.15g (would append to candidates.jsonl)\n",
                   (unsigned long long)w, o.pmax);
        if (o.pmax > best) { best = o.pmax; bw = w; }
    }
    const double ref = 6.825835461843649;
    int ok = (bw == 2149309687ULL) && fabs(best - ref) <= 1e-9;
    printf("V3 drill [%llu,%llu): best word %llu pmax %.15g (ref 2149309687 @ %.15g) -> %s\n",
           (unsigned long long)a, (unsigned long long)b, (unsigned long long)bw, best, ref,
           ok ? "PASS" : "FAIL");
    free(cx); free(st);
    return ok ? 0 : 1;
}

static int bench(uint64_t n, int nthreads) {
    Lane ln = lane_S1();
    StepTab *st = calloc(LSCREEN, sizeof(StepTab));
    build_steps(C_SCREEN, st);
    const uint64_t start = 3000000ULL;
    double t0 = omp_get_wtime();
    double best = -1e30; uint64_t bw = 0; uint64_t ncand = 0;
    #pragma omp parallel num_threads(nthreads)
    {
        Ctx *cx = calloc(1, sizeof(Ctx));
        double lbest = -1e30; uint64_t lbw = 0, lc = 0;
        #pragma omp for schedule(static)
        for (uint64_t w = start; w < start + n; w++) {
            DecOut o = screen_one(&ln, st, C_SCREEN, cx, (uint32_t)w);
            if (o.pmax > lbest) { lbest = o.pmax; lbw = w; }
            if (o.pmax >= ln.cand_bar) lc++;
        }
        #pragma omp critical
        { if (lbest > best) { best = lbest; bw = lbw; } ncand += lc; }
        free(cx);
    }
    double dt = omp_get_wtime() - t0;
    printf("bench: %llu seeds, %d threads, %.2f s -> %.0f seeds/s aggregate "
           "(%.0f /s/thread); best pmax %.6f @ %llu; candidates>=%.1f: %llu\n",
           (unsigned long long)n, nthreads, dt, n / dt, n / dt / nthreads,
           best, (unsigned long long)bw, ln.cand_bar, (unsigned long long)ncand);
    free(st);
    return 0;
}

/* ------------------------------------------------------------------ tiny JSON helpers (files we author) */
static char *slurp(const char *path, long *len) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    fseek(f, 0, SEEK_END); long n = ftell(f); fseek(f, 0, SEEK_SET);
    char *b = malloc((size_t)n + 1);
    if (fread(b, 1, (size_t)n, f) != (size_t)n) { fclose(f); free(b); return NULL; }
    b[n] = 0; fclose(f);
    if (len) *len = n;
    return b;
}

/* find `"key"` inside [s,e), return pointer just past the ':' (NULL if absent) */
static const char *jkey(const char *s, const char *e, const char *key) {
    char pat[80]; snprintf(pat, sizeof pat, "\"%s\"", key);
    size_t pl = strlen(pat);
    for (const char *p = s; p + pl < e; p++) {
        if (!memcmp(p, pat, pl)) {
            const char *q = p + pl;
            while (q < e && (*q == ' ' || *q == '\t' || *q == '\n' || *q == '\r')) q++;
            if (q < e && *q == ':') return q + 1;
        }
    }
    return NULL;
}

static double jnum(const char *s, const char *e, const char *key, double dflt) {
    const char *p = jkey(s, e, key);
    return p ? strtod(p, NULL) : dflt;
}

static int jstr(const char *s, const char *e, const char *key, char *out, int cap) {
    const char *p = jkey(s, e, key);
    if (!p) return 0;
    while (p < e && *p != '"') p++;
    if (p >= e) return 0;
    p++;
    int i = 0;
    while (p < e && *p != '"' && i < cap - 1) out[i++] = *p++;
    out[i] = 0;
    return 1;
}

/* iterate top-level {...} objects inside the [] that starts at *pp; returns spans */
static int jnext_obj(const char **pp, const char *e, const char **os, const char **oe) {
    const char *p = *pp;
    while (p < e && *p != '{') { if (*p == ']') return 0; p++; }
    if (p >= e) return 0;
    int depth = 0; const char *q = p;
    while (q < e) {
        if (*q == '{') depth++;
        else if (*q == '}') { depth--; if (!depth) break; }
        q++;
    }
    if (q >= e) return 0;
    *os = p; *oe = q + 1; *pp = q + 1;
    return 1;
}

/* ------------------------------------------------------------------ sweep-plan runner */
static volatile sig_atomic_t G_STOP = 0;
static void on_sig(int s) { (void)s; G_STOP = 1; }

typedef struct {
    uint64_t band_start, band_end;
    volatile uint64_t cursor;
    volatile uint64_t seeds_done;
    volatile uint64_t n_cand;
    double best_pmax;              /* owner-thread written */
    uint64_t best_word;
    int done;
} Worker;

typedef struct { uint64_t seed; double pmax; } Top;

static char G_RUNDIR[1024] = ".";
static char G_PLANPATH[1024] = "";
static Worker G_W[MAX_WORKERS];
static int G_NW = 6;
static uint64_t *G_HIST;           /* nw * HIST_BINS */
static Top G_TOP[TOPK]; static int G_NTOP = 0;   /* min-heap on pmax */
static FILE *G_CANDF = NULL;
static Top G_HITS[MAX_HITS]; static int G_NHITS = 0;
static char G_DONE_LANES[MAX_LANES][32]; static int G_NDONE = 0;
static double G_RUN_T0; static uint64_t G_RUN_DONE0;

static void heap_push(uint64_t seed, double pm) {
    if (G_NTOP < TOPK) {
        int i = G_NTOP++;
        G_TOP[i].seed = seed; G_TOP[i].pmax = pm;
        while (i && G_TOP[(i-1)/2].pmax > G_TOP[i].pmax) {
            Top t = G_TOP[i]; G_TOP[i] = G_TOP[(i-1)/2]; G_TOP[(i-1)/2] = t; i = (i-1)/2;
        }
        return;
    }
    if (pm <= G_TOP[0].pmax) return;
    G_TOP[0].seed = seed; G_TOP[0].pmax = pm;
    int i = 0;
    for (;;) {
        int l = 2*i+1, r = 2*i+2, m = i;
        if (l < TOPK && G_TOP[l].pmax < G_TOP[m].pmax) m = l;
        if (r < TOPK && G_TOP[r].pmax < G_TOP[m].pmax) m = r;
        if (m == i) break;
        Top t = G_TOP[i]; G_TOP[i] = G_TOP[m]; G_TOP[m] = t; i = m;
    }
}

static int top_cmp_desc(const void *a, const void *b) {
    const Top *x = a, *y = b;
    if (x->pmax != y->pmax) return x->pmax > y->pmax ? -1 : 1;
    return x->seed < y->seed ? -1 : x->seed > y->seed ? 1 : 0;
}

