/* Round 27 / P1 -- grind27.c -- C port of the R25 Py2.7-MT 2^32 derived-key grind.
 *
 * Source of truth: analysis/round27/P0-spec/SPEC.md (authoritative) and
 * vectors.json (64-seed reference vectors + planted controls). This engine is the
 * STAGE-A SCREEN ONLY (SPEC section 0): it makes NO hit decision -- its only filter
 * is the candidate bar 5.0, and every seed at/above it is appended to
 * candidates.jsonl for the Python adjudicator (hitfn20) to re-score. A seed whose
 * pmax also reaches the lane claim bar additionally lands in HIT-CANDIDATE.json
 * (FLAGGED-FOR-ORACLE pending Python stage_b; the sweep KEEPS GOING).
 *
 * Pipeline per seed w (SPEC sections 1-4, replicated bit-for-bit):
 *   MT19937 init_by_array([w])  (CPython 2.7 semantics == mt19937ar verbatim)
 *   -> reducer (random29: ks[i] = (int)(random()*29), 2 draws/rune)
 *   -> 784-rune keystream, zero-padded to 784 + L*(max_skip+1)+8   (section 3.1)
 *   -> driftbeam beam decode of C_SCREEN[0:120], sign=-1, beam_w=64,
 *      relation 'pair' (keyskip2, max_skip=8) or 'exact' (keyskip1, max_skip=3)
 *   -> 9-register trigram panel-max z-score at n=120 (frozen mu/sd from vectors.json)
 *
 * Input data: engine.dat + panel_lm.f32, generated by export_data.py FROM
 * vectors.json + round19/I2/models/panel.npz (the same panel.npz that generated
 * vectors.json; sha256 recorded in engine.dat). The ciphertext is loaded from that
 * export of vectors.json, never re-derived. The quadgram model is parsed directly
 * from data/english_quadgrams.txt (path recorded in engine.dat) with the exact
 * lp/score.py arithmetic: d[q] = log10(count) - log10(total), floor
 * log10(0.01) - log10(total).
 *
 * Build (BUILD.md):
 *   gcc -O3 -march=native -fopenmp -std=gnu17 -ffp-contract=off -o grind27 grind27.c -lm
 *
 * Modes:
 *   ./grind27 --self-test                          V1 (64-vector parity) + V2 (planted screen)
 *   ./grind27 --drill                              V3 band [2149309680,2149309700)
 *   ./grind27 --bench N                            throughput over N seeds
 *   ./grind27 --plan sweep_plan.json --run-dir D   the checkpointed sweep-plan runner
 *   ./grind27 --status --run-dir D                 print STATUS.json (no worker contact)
 */
