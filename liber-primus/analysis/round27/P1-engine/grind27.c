static void write_status(const Lane *ln, int final) {
    char p[1200]; snprintf(p, sizeof p, "%s/STATUS.json", G_RUNDIR);
    char tp[1220]; snprintf(tp, sizeof tp, "%s.tmp", p);
    FILE *f = fopen(tp, "w");
    if (!f) return;
    uint64_t done = 0, cov = 0, cand = 0;
    double best = -1e30; uint64_t bw = 0;
    for (int i = 0; i < G_NW; i++) {
        done += G_W[i].seeds_done;
        cov  += G_W[i].cursor - G_W[i].band_start;
        cand += G_W[i].n_cand;
        if (G_W[i].best_pmax > best) { best = G_W[i].best_pmax; bw = G_W[i].best_word; }
    }
    double dt = omp_get_wtime() - G_RUN_T0;
    double thr = dt > 0 ? (double)(done - G_RUN_DONE0) / dt : 0.0;
    fprintf(f, "{\n \"engine\": \"grind27\", \"plan_path\": \"%s\",\n"
               " \"current_lane\": \"%s\", \"relation\": \"%s\", \"reducer_id\": %d,"
               " \"offset\": %d,\n \"from\": %llu, \"to\": %llu,\n"
               " \"cand_bar\": %.17g, \"claim_bar\": %.17g,\n",
            G_PLANPATH, ln->name, ln->pair ? "pair" : "exact", ln->reducer, ln->offset,
            (unsigned long long)ln->from, (unsigned long long)ln->to,
            ln->cand_bar, ln->claim_bar);
    fprintf(f, " \"lanes_completed\": [");
    for (int i = 0; i < G_NDONE; i++)
        fprintf(f, "%s\"%s\"", i ? ", " : "", G_DONE_LANES[i]);
    fprintf(f, "],\n \"workers\": [\n");
    for (int i = 0; i < G_NW; i++) {
        Worker *w = &G_W[i];
        fprintf(f, "  {\"worker\": %d, \"band_start\": %llu, \"band_end\": %llu,"
                   " \"cursor\": %llu, \"seeds_done\": %llu,"
                   " \"seeds_skipped_excluded\": 0, \"best_pmax\": %.17g,"
                   " \"best_word\": %llu, \"n_candidates\": %llu,"
                   " \"flagged_survivors\": [], \"done\": %s}%s\n",
                i, (unsigned long long)w->band_start, (unsigned long long)w->band_end,
                (unsigned long long)w->cursor, (unsigned long long)w->seeds_done,
                w->best_pmax, (unsigned long long)w->best_word,
                (unsigned long long)w->n_cand,
                w->done ? "true" : "false", i + 1 < G_NW ? "," : "");
    }
    fprintf(f, " ],\n \"aggregate\": {\"seeds_done\": %llu,"
               " \"lane_words_covered\": %llu, \"lane_coverage_fraction\": %.9f,"
               " \"best_pmax\": %.17g, \"best_word\": %llu, \"n_candidates\": %llu,"
               " \"n_claim_bar_hits\": %d, \"throughput_seeds_per_s\": %.1f},\n",
            (unsigned long long)done, (unsigned long long)cov,
            (double)cov / (double)(ln->to - ln->from), best, (unsigned long long)bw,
            (unsigned long long)cand, G_NHITS, thr);
    fprintf(f, " \"final_flush\": %s, \"updated_unix\": %ld\n}\n",
            final ? "true" : "false", (long)time(NULL));
    fclose(f);
    rename(tp, p);
}

static void flush_all(const Lane *ln, int final) {
    write_status(ln, final);
    /* per-worker pmax histogram (uint64 LE, nw x 2600 bins of 0.01 over [0,26)) */
    char p[1200]; snprintf(p, sizeof p, "%s/hist_%s.u64", G_RUNDIR, ln->name);
    char tp[1220]; snprintf(tp, sizeof tp, "%s.tmp", p);
    FILE *f = fopen(tp, "wb");
    if (f) {
        fwrite(G_HIST, sizeof(uint64_t), (size_t)G_NW * HIST_BINS, f);
        fclose(f); rename(tp, p);
    }
    /* global top-1024 */
    snprintf(p, sizeof p, "%s/top_%s.json", G_RUNDIR, ln->name);
    snprintf(tp, sizeof tp, "%s.tmp", p);
    f = fopen(tp, "w");
    if (f) {
        Top sorted[TOPK];
        memcpy(sorted, G_TOP, sizeof(Top) * (size_t)G_NTOP);
        qsort(sorted, (size_t)G_NTOP, sizeof(Top), top_cmp_desc);
        fprintf(f, "[\n");
        for (int i = 0; i < G_NTOP; i++)
            fprintf(f, " {\"seed\": %llu, \"pmax\": %.17g}%s\n",
                    (unsigned long long)sorted[i].seed, sorted[i].pmax,
                    i + 1 < G_NTOP ? "," : "");
        fprintf(f, "]\n");
        fclose(f); rename(tp, p);
    }
    if (G_CANDF) { fflush(G_CANDF); fsync(fileno(G_CANDF)); }
}

static void load_lane_state(const Lane *ln) {
    /* resume: STATUS.json (cursors) + hist + top for THIS lane, if present */
    char p[2048]; long n;
    snprintf(p, sizeof p, "%s/STATUS.json", G_RUNDIR);
    char *s = slurp(p, &n);
    if (s) {
        char cur[64] = "";
        jstr(s, s + n, "current_lane", cur, sizeof cur);
        if (!strcmp(cur, ln->name)) {
            const char *wa = jkey(s, s + n, "workers");
            if (wa) {
                const char *pp = wa, *os, *oe; int i = 0;
                while (i < G_NW && jnext_obj(&pp, s + n, &os, &oe)) {
                    G_W[i].band_start = (uint64_t)jnum(os, oe, "band_start", (double)G_W[i].band_start);
                    G_W[i].band_end   = (uint64_t)jnum(os, oe, "band_end", (double)G_W[i].band_end);
                    G_W[i].cursor     = (uint64_t)jnum(os, oe, "cursor", (double)G_W[i].band_start);
                    G_W[i].seeds_done = (uint64_t)jnum(os, oe, "seeds_done", 0);
                    G_W[i].n_cand     = (uint64_t)jnum(os, oe, "n_candidates", 0);
                    G_W[i].best_pmax  = jnum(os, oe, "best_pmax", -1e30);
                    G_W[i].best_word  = (uint64_t)jnum(os, oe, "best_word", 0);
                    G_W[i].done       = G_W[i].cursor >= G_W[i].band_end;
                    i++;
                }
                if (i == G_NW)
                    printf("resumed lane %s from STATUS.json\n", ln->name);
            }
        }
        free(s);
    }
    snprintf(p, sizeof p, "%s/hist_%s.u64", G_RUNDIR, ln->name);
    FILE *f = fopen(p, "rb");
    if (f) {
        if (fread(G_HIST, sizeof(uint64_t), (size_t)G_NW * HIST_BINS, f)
            != (size_t)G_NW * HIST_BINS)
            memset(G_HIST, 0, sizeof(uint64_t) * (size_t)G_NW * HIST_BINS);
        fclose(f);
    }
    snprintf(p, sizeof p, "%s/top_%s.json", G_RUNDIR, ln->name);
    s = slurp(p, &n);
    if (s) {
        const char *pp = s, *os, *oe;
        while (jnext_obj(&pp, s + n, &os, &oe)) {
            uint64_t seed = (uint64_t)jnum(os, oe, "seed", 0);
            double pm = jnum(os, oe, "pmax", -1e30);
            if (pm > -1e29) heap_push(seed, pm);
        }
        free(s);
    }
}

/* returns 0 = lane completed, 1 = interrupted (time/signal) */
static int run_lane(const Lane *ln, double seconds) {
    StepTab *st = calloc(LSCREEN, sizeof(StepTab));
    build_steps(C_SCREEN, st);

    /* fresh band partition (overridden by resume if STATUS matches this lane) */
    uint64_t total = ln->to - ln->from, step = total / (uint64_t)G_NW;
    for (int i = 0; i < G_NW; i++) {
        G_W[i].band_start = ln->from + (uint64_t)i * step;
        G_W[i].band_end = (i == G_NW - 1) ? ln->to : ln->from + (uint64_t)(i + 1) * step;
        G_W[i].cursor = G_W[i].band_start;
        G_W[i].seeds_done = 0; G_W[i].n_cand = 0;
        G_W[i].best_pmax = -1e30; G_W[i].best_word = 0; G_W[i].done = 0;
    }
    memset(G_HIST, 0, sizeof(uint64_t) * (size_t)G_NW * HIST_BINS);
    G_NTOP = 0; G_NHITS = 0;
    load_lane_state(ln);

    uint64_t pre_done = 0;
    for (int i = 0; i < G_NW; i++) pre_done += G_W[i].seeds_done;
    G_RUN_T0 = omp_get_wtime(); G_RUN_DONE0 = pre_done;

    printf("lane %s: relation=%s reducer=%d offset=%d [%llu, %llu) cand_bar=%.3f "
           "claim_bar=%.6f workers=%d\n", ln->name, ln->pair ? "pair" : "exact",
           ln->reducer, ln->offset, (unsigned long long)ln->from,
           (unsigned long long)ln->to, ln->cand_bar, ln->claim_bar, G_NW);
    for (int i = 0; i < G_NW; i++)
        printf("  w%d band [%llu, %llu) cursor=%llu%s\n", i,
               (unsigned long long)G_W[i].band_start, (unsigned long long)G_W[i].band_end,
               (unsigned long long)G_W[i].cursor, G_W[i].done ? " [done]" : "");
    fflush(stdout);

    double t_deadline = seconds > 0 ? omp_get_wtime() + seconds : 0;
    volatile int alldone = 0;

    #pragma omp parallel num_threads(G_NW)
    {
        int wi = omp_get_thread_num();
        Worker *W = &G_W[wi];
        Ctx *cx = calloc(1, sizeof(Ctx));
        uint64_t *hist = G_HIST + (size_t)wi * HIST_BINS;
        double next_ckpt = omp_get_wtime() + CKPT_EVERY;
        uint64_t w = W->cursor;
        uint64_t lbest_w = W->best_word; double lbest = W->best_pmax;
        int check = 0;

        while (w < W->band_end) {
            if (++check >= 256) {          /* cheap periodic checks */
                check = 0;
                W->cursor = w;
                if (G_STOP) break;
                if (t_deadline > 0 && omp_get_wtime() > t_deadline) break;
                if (wi == 0 && omp_get_wtime() >= next_ckpt) {
                    flush_all(ln, 0);
                    next_ckpt = omp_get_wtime() + CKPT_EVERY;
                }
            }
            DecOut o = screen_one(ln, st, C_SCREEN, cx, (uint32_t)w);
            W->seeds_done++;
            int bin = (int)(o.pmax * 100.0);
            if (bin < 0) bin = 0;
            if (bin >= HIST_BINS) bin = HIST_BINS - 1;
            hist[bin]++;
            if (o.pmax > lbest) {
                lbest = o.pmax; lbest_w = w;
                W->best_pmax = lbest; W->best_word = lbest_w;
            }
            if (G_NTOP < TOPK || o.pmax > G_TOP[0].pmax) {
                #pragma omp critical(topheap)
                heap_push(w, o.pmax);
            }
            if (o.pmax >= ln->cand_bar) {
                /* NEVER silently drop anything near the bar (SPEC section 0) */
                #pragma omp critical(candout)
                {
                    fprintf(G_CANDF, "{\"lane\": \"%s\", \"seed\": %llu, \"pmax\": %.17g}\n",
                            ln->name, (unsigned long long)w, o.pmax);
                    fflush(G_CANDF);
                    W->n_cand++;
                    if (o.pmax >= ln->claim_bar && G_NHITS < MAX_HITS) {
                        G_HITS[G_NHITS].seed = w; G_HITS[G_NHITS].pmax = o.pmax; G_NHITS++;
                        write_hits_file(ln);
                        printf("*** claim-bar candidate (KEEP SWEEPING): lane %s seed %llu "
                               "pmax %.9f >= %.9f -- FLAGGED-FOR-ORACLE pending Python "
                               "stage_b ***\n", ln->name, (unsigned long long)w, o.pmax,
                               ln->claim_bar);
                        fflush(stdout);
                    }
                }
            }
            w++;
        }
        W->cursor = w;
        if (w >= W->band_end) W->done = 1;
        free(cx);

        /* worker 0 keeps flushing while others still run */
        if (wi == 0) {
            for (;;) {
                int nd = 1;
                for (int i = 1; i < G_NW; i++)
                    if (!G_W[i].done && G_W[i].cursor < G_W[i].band_end) nd = 0;
                if (nd || G_STOP) break;
                if (t_deadline > 0 && omp_get_wtime() > t_deadline) break;
                struct timespec ts = {1, 0}; nanosleep(&ts, NULL);
                if (omp_get_wtime() >= next_ckpt) {
                    flush_all(ln, 0);
                    next_ckpt = omp_get_wtime() + CKPT_EVERY;
                }
            }
        }
    }

    alldone = 1;
    for (int i = 0; i < G_NW; i++) if (!G_W[i].done) alldone = 0;
    flush_all(ln, alldone);
    free(st);
    return alldone ? 0 : 1;
}

static int run_plan(const char *plan_path, double seconds) {
    long n;
    char *s = slurp(plan_path, &n);
    if (!s) die("cannot read sweep plan");
    Lane lanes[MAX_LANES]; int nl = 0;
    const char *pp = s, *os, *oe;
    while (nl < MAX_LANES && jnext_obj(&pp, s + n, &os, &oe)) {
        Lane *ln = &lanes[nl]; memset(ln, 0, sizeof *ln);
        char buf[64];
        if (!jstr(os, oe, "lane", ln->name, sizeof ln->name)) die("plan: lane name");
        if (!jstr(os, oe, "relation", buf, sizeof buf)) die("plan: relation");
        if (!strcmp(buf, "pair")) ln->pair = 1;
        else if (!strcmp(buf, "exact")) ln->pair = 0;
        else die("plan: relation must be 'pair' or 'exact'");
        if (!jstr(os, oe, "reducer", buf, sizeof buf)) die("plan: reducer");
        ln->reducer = reducer_from_name(buf);
        if (ln->reducer < 0) die("plan: unknown reducer");
        ln->offset = (int)jnum(os, oe, "offset", 0);
        ln->from = (uint64_t)jnum(os, oe, "from", 0);
        ln->to = (uint64_t)jnum(os, oe, "to", 4294967296.0);
        ln->cand_bar = jnum(os, oe, "cand_bar", 0);
        ln->claim_bar = jnum(os, oe, "claim_bar", 0);
        lane_finish_init(ln);
        nl++;
    }
    free(s);
    if (!nl) die("empty sweep plan");
    snprintf(G_PLANPATH, sizeof G_PLANPATH, "%s", plan_path);

    /* completed-lane list from a previous STATUS.json */
    char p[1200]; snprintf(p, sizeof p, "%s/STATUS.json", G_RUNDIR);
    char *st = slurp(p, &n);
    if (st) {
        const char *la = jkey(st, st + n, "lanes_completed");
        if (la) {
            const char *q = la;
            while (q < st + n && *q != ']') {
                if (*q == '"') {
                    q++;
                    char nm[32]; int i = 0;
                    while (q < st + n && *q != '"' && i < 31) nm[i++] = *q++;
                    nm[i] = 0;
                    if (G_NDONE < MAX_LANES) strcpy(G_DONE_LANES[G_NDONE++], nm);
                }
                q++;
            }
        }
        free(st);
    }

    G_HIST = calloc((size_t)G_NW * HIST_BINS, sizeof(uint64_t));
    snprintf(p, sizeof p, "%s/candidates.jsonl", G_RUNDIR);
    G_CANDF = fopen(p, "a");
    if (!G_CANDF) die("cannot open candidates.jsonl for append");

    signal(SIGINT, on_sig);
    signal(SIGTERM, on_sig);

    int rc = 0;
    for (int i = 0; i < nl; i++) {
        int skip = 0;
        for (int j = 0; j < G_NDONE; j++)
            if (!strcmp(G_DONE_LANES[j], lanes[i].name)) skip = 1;
        if (skip) { printf("lane %s already completed; skipping\n", lanes[i].name); continue; }
        if (!lanes[i].pair && !getenv("GRIND27_S2_CONTROL_OK")) {
            /* PREREG gate: the launch-time self-test only validates the 'pair' relation.
             * An 'exact' lane needs its own planted control + V1-style vectors BEFORE
             * its null counts (sweep_plan S2 note). Refuse until that control exists. */
            printf("REFUSING lane %s: relation 'exact' has no planted control/vector "
                   "file yet (PREREG S2 gate). Build + validate the exact-relation "
                   "control, then set GRIND27_S2_CONTROL_OK=1 to unblock.\n",
                   lanes[i].name);
            rc = 1;
            break;
        }
        int r = run_lane(&lanes[i], seconds);
        if (r == 0) {
            if (G_NDONE < MAX_LANES) strcpy(G_DONE_LANES[G_NDONE++], lanes[i].name);
            write_status(&lanes[i], 1);
            printf("lane %s COMPLETE (coverage 1.0 of [%llu,%llu))\n", lanes[i].name,
                   (unsigned long long)lanes[i].from, (unsigned long long)lanes[i].to);
        } else {
            printf("lane %s interrupted (checkpointed; re-run to resume)\n", lanes[i].name);
            rc = 1;
            break;
        }
    }
    fclose(G_CANDF);
    return rc;
}

static int show_status(void) {
    char p[1200]; long n;
    snprintf(p, sizeof p, "%s/STATUS.json", G_RUNDIR);
    char *s = slurp(p, &n);
    if (!s) { printf("no STATUS.json in %s\n", G_RUNDIR); return 1; }
    fwrite(s, 1, (size_t)n, stdout);
    free(s);
    return 0;
}

/* ------------------------------------------------------------------ P2 ENGINE-CONTRACT modes
 * (score / sweep / self-test as specified in P2-harness/ENGINE-CONTRACT.md).
 * CRITICAL: StepTab is cipher-dependent -- any --cipher override rebuilds the step
 * tables (same lesson as the V2 planted screen). */

/* parse --cipher JSON {"cipher_idx": [...]}; fills C_out[LSCREEN] (first 120 entries) */
static void load_cipher_override(const char *path, int *C_out) {
    long n;
    char *s = slurp(path, &n);
    if (!s) die("cannot read --cipher file");
    const char *p = jkey(s, s + n, "cipher_idx");
    if (!p) die("--cipher file lacks \"cipher_idx\"");
    while (p < s + n && *p != '[') p++;
    if (p >= s + n) die("--cipher: cipher_idx is not an array");
    p++;
    int i = 0;
    while (i < LSCREEN && p < s + n) {
        while (p < s + n && (*p == ' ' || *p == ',' || *p == '\t' || *p == '\n' || *p == '\r')) p++;
        if (p >= s + n || *p == ']') break;
        char *end;
        long v = strtol(p, &end, 10);
        if (end == p) die("--cipher: bad integer in cipher_idx");
        if (v < 0 || v >= NRUNE) die("--cipher: rune index out of [0,29)");
        C_out[i++] = (int)v;
        p = end;
    }
    free(s);
    if (i != LSCREEN) die("--cipher: need at least 120 cipher_idx entries");
}

/* --mode score: one u32/line in, one JSON object per line out, INPUT ORDER preserved */
static int mode_score(const char *seeds_path, const char *out_path, int full,
                      const int *cipher) {
    FILE *fi = fopen(seeds_path, "r");
    if (!fi) die("cannot open --seeds file");
    FILE *fo = fopen(out_path, "w");
    if (!fo) die("cannot open --out file");
    Lane ln = lane_S1();
    StepTab *st = calloc(LSCREEN, sizeof(StepTab));
    build_steps(cipher, st);
    Ctx *cx = calloc(1, sizeof(Ctx));
    char line[128];
    while (fgets(line, sizeof line, fi)) {
        char *p = line;
        while (*p == ' ' || *p == '\t') p++;
        if (*p == '\n' || *p == '\r' || !*p) continue;
        uint32_t w = (uint32_t)strtoull(p, NULL, 10);
        DecOut o = screen_one(&ln, st, cipher, cx, w);
        if (!full) {
            fprintf(fo, "{\"seed\": %u, \"pmax\": %.17g}\n", w, o.pmax);
        } else {
            fprintf(fo, "{\"seed\": %u, \"pmax\": %.17g, \"ks128\": [", w, o.pmax);
            for (int i = 0; i < 128; i++) fprintf(fo, "%s%d", i ? ", " : "", cx->Kx[i]);
            fprintf(fo, "], \"plain_idx\": [");
            for (int i = 0; i < LSCREEN; i++) fprintf(fo, "%s%d", i ? ", " : "", cx->plain[i]);
            fprintf(fo, "], \"ptr_end\": %d, \"n_skips\": %d, \"nchars\": %d}\n",
                    o.ptr_end, o.n_skips, o.nchars);
        }
    }
    fclose(fi); fclose(fo);
    free(cx); free(st);
    return 0;
}

/* --mode sweep: banded live sweep over [a,b); appends candidates >= cand_bar to out;
 * final stdout JSON summary. Same screen_one kernel + banding shape as run_lane. */
static int mode_sweep(uint64_t a, uint64_t b, int nthreads, const char *out_path,
                      const int *cipher, const char *progress_dir) {
    if (b <= a) die("--mode sweep: band-end must exceed band-start");
    Lane ln = lane_S1();
    StepTab *st = calloc(LSCREEN, sizeof(StepTab));
    build_steps(cipher, st);
    FILE *fo = fopen(out_path, "a");
    if (!fo) die("cannot open --out for append");
    static uint64_t wlo[MAX_WORKERS], whi[MAX_WORKERS], wdone[MAX_WORKERS],
                    wcand[MAX_WORKERS], wbw[MAX_WORKERS];
    static double wbest[MAX_WORKERS];
    const uint64_t total = b - a, step = total / (uint64_t)nthreads;
    for (int i = 0; i < nthreads; i++) {
        wlo[i] = a + (uint64_t)i * step;
        whi[i] = (i == nthreads - 1) ? b : a + (uint64_t)(i + 1) * step;
        wdone[i] = wcand[i] = wbw[i] = 0;
        wbest[i] = -1e30;
    }
    double t0 = omp_get_wtime();
    #pragma omp parallel num_threads(nthreads)
    {
        int wi = omp_get_thread_num();
        Ctx *cx = calloc(1, sizeof(Ctx));
        for (uint64_t w = wlo[wi]; w < whi[wi]; w++) {
            DecOut o = screen_one(&ln, st, cipher, cx, (uint32_t)w);
            wdone[wi]++;
            if (o.pmax > wbest[wi]) { wbest[wi] = o.pmax; wbw[wi] = w; }
            if (o.pmax >= ln.cand_bar) {
                wcand[wi]++;
                #pragma omp critical(sweepout)
                {
                    fprintf(fo, "{\"seed\": %llu, \"pmax\": %.17g}\n",
                            (unsigned long long)w, o.pmax);
                    fflush(fo);
                }
            }
        }
        free(cx);
    }
    double dt = omp_get_wtime() - t0;
    fclose(fo);
    uint64_t done = 0, ncand = 0;
    double best = -1e30; uint64_t bw = 0;
    for (int i = 0; i < nthreads; i++) {
        done += wdone[i]; ncand += wcand[i];
        if (wbest[i] > best) { best = wbest[i]; bw = wbw[i]; }
    }
    if (progress_dir) {                    /* SPEC section-6-compatible per-worker files */
        for (int i = 0; i < nthreads; i++) {
            char p[1200]; snprintf(p, sizeof p, "%s/progress_w%d.json", progress_dir, i);
            FILE *f = fopen(p, "w");
            if (!f) continue;
            fprintf(f, "{\"worker\": %d, \"band_start\": %llu, \"band_end\": %llu,"
                       " \"cursor\": %llu, \"seeds_done\": %llu, \"best_pmax\": %.17g,"
                       " \"best_word\": %llu, \"n_candidates\": %llu, \"done\": true}\n",
                    i, (unsigned long long)wlo[i], (unsigned long long)whi[i],
                    (unsigned long long)whi[i], (unsigned long long)wdone[i], wbest[i],
                    (unsigned long long)wbw[i], (unsigned long long)wcand[i]);
            fclose(f);
        }
    }
    printf("{\"mode\": \"sweep\", \"seeds_done\": %llu, \"elapsed_s\": %.3f,"
           " \"band_start\": %llu, \"band_end\": %llu, \"threads\": %d,"
           " \"n_candidates\": %llu, \"best_pmax\": %.17g, \"best_word\": %llu}\n",
           (unsigned long long)done, dt, (unsigned long long)a, (unsigned long long)b,
           nthreads, (unsigned long long)ncand, best, (unsigned long long)bw);
    free(st);
    return 0;
}

/* ------------------------------------------------------------------ main */
int main(int argc, char **argv) {
    int do_selftest = 0, do_drill = 0, do_status = 0;
    uint64_t bench_n = 0;
    const char *plan = NULL;
    double seconds = 0;
    char dat_path[1200];

    /* engine.dat lives next to the binary's source dir by convention; allow override */
    snprintf(dat_path, sizeof dat_path, "engine.dat");
    {   /* prefer engine.dat next to the executable */
        char exe[1024]; ssize_t r = readlink("/proc/self/exe", exe, sizeof exe - 1);
        if (r > 0) {
            exe[r] = 0;
            char *sl = strrchr(exe, '/');
            if (sl) { *sl = 0; snprintf(dat_path, sizeof dat_path, "%s/engine.dat", exe); }
        }
    }

    /* P2 ENGINE-CONTRACT flags (P2-harness/ENGINE-CONTRACT.md) */
    const char *mode = NULL, *seeds_path = NULL, *out_path = NULL;
    const char *cipher_path = NULL, *progress_dir = NULL;
    int full = 0;
    uint64_t band_start = 0, band_end = 0;
    int have_bs = 0, have_be = 0;

    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--self-test")) do_selftest = 1;
        else if (!strcmp(argv[i], "--drill")) do_drill = 1;
        else if (!strcmp(argv[i], "--status")) do_status = 1;
        else if (!strcmp(argv[i], "--bench") && i + 1 < argc) bench_n = strtoull(argv[++i], NULL, 10);
        else if (!strcmp(argv[i], "--plan") && i + 1 < argc) plan = argv[++i];
        else if (!strcmp(argv[i], "--run-dir") && i + 1 < argc)
            snprintf(G_RUNDIR, sizeof G_RUNDIR, "%s", argv[++i]);
        else if (!strcmp(argv[i], "--seconds") && i + 1 < argc) seconds = atof(argv[++i]);
        else if (!strcmp(argv[i], "--threads") && i + 1 < argc) G_NW = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--data") && i + 1 < argc)
            snprintf(dat_path, sizeof dat_path, "%s", argv[++i]);
        /* -- contract flags -- */
        else if (!strcmp(argv[i], "--vectors") && i + 1 < argc) i++;   /* accepted; engine
            loads the identical data via engine.dat (exported FROM vectors.json) */
        else if (!strcmp(argv[i], "--lm") && i + 1 < argc) i++;        /* ditto (sha256 of
            panel_lm.f32 is verified against panel.npz by check_vectors) */
        else if (!strcmp(argv[i], "--mode") && i + 1 < argc) mode = argv[++i];
        else if (!strcmp(argv[i], "--seeds") && i + 1 < argc) seeds_path = argv[++i];
        else if (!strcmp(argv[i], "--out") && i + 1 < argc) out_path = argv[++i];
        else if (!strcmp(argv[i], "--full")) full = 1;
        else if (!strcmp(argv[i], "--cipher") && i + 1 < argc) cipher_path = argv[++i];
        else if (!strcmp(argv[i], "--band-start") && i + 1 < argc)
            { band_start = strtoull(argv[++i], NULL, 10); have_bs = 1; }
        else if (!strcmp(argv[i], "--band-end") && i + 1 < argc)
            { band_end = strtoull(argv[++i], NULL, 10); have_be = 1; }
        else if (!strcmp(argv[i], "--progress-dir") && i + 1 < argc) progress_dir = argv[++i];
        else { fprintf(stderr, "unknown arg %s\n", argv[i]); return 1; }
    }
    if (G_NW < 1 || G_NW > MAX_WORKERS) die("--threads out of range");

    if (do_status) return show_status();

    init_tables();
    load_engine_dat(dat_path);
    load_quadgrams();
    load_panel();

    if (mode) {                            /* ---- P2 ENGINE-CONTRACT dispatch ---- */
        int cipher[LSCREEN];
        memcpy(cipher, C_SCREEN, sizeof cipher);
        if (cipher_path) load_cipher_override(cipher_path, cipher);
        if (!strcmp(mode, "self-test")) {
            DecOut o;
            memset(&o, 0, sizeof o);
            int st_rc = self_test(&o);     /* full V1+V2 (K3-grade), plant DecOut out */
            int cand = o.pmax >= G_CAND_BAR;
            printf("{\"mode\": \"self-test\", \"seed\": %d, \"pmax\": %.17g,"
                   " \"candidate\": %s}\n", G_PLANT_SEED, o.pmax, cand ? "true" : "false");
            return (st_rc == 0 && cand) ? 0 : 1;
        }
        if (!strcmp(mode, "score")) {
            if (!seeds_path || !out_path) die("--mode score needs --seeds and --out");
            return mode_score(seeds_path, out_path, full, cipher);
        }
        if (!strcmp(mode, "sweep")) {
            if (!out_path || !have_bs || !have_be)
                die("--mode sweep needs --band-start, --band-end and --out");
            return mode_sweep(band_start, band_end, G_NW, out_path, cipher, progress_dir);
        }
        fprintf(stderr, "unknown --mode %s (score|sweep|self-test)\n", mode);
        return 1;
    }

    if (do_selftest) return self_test(NULL);
    if (do_drill) {
        if (self_test(NULL)) { printf("refusing drill: self-test failed\n"); return 1; }
        return drill();
    }
    if (bench_n) return bench(bench_n, G_NW);
    if (plan) {
        /* K3 (PREREG): planted screen control must pass at every launch/restart */
        if (self_test(NULL)) { printf("ABORT: self-test failed; broken scan, not a null\n"); return 1; }
        return run_plan(plan, seconds);
    }
    fprintf(stderr, "usage: grind27 --self-test | --drill | --bench N | "
                    "--plan sweep_plan.json --run-dir DIR [--seconds S] [--threads N] | "
                    "--status --run-dir DIR | "
                    "--mode score|sweep|self-test [contract flags per "
                    "P2-harness/ENGINE-CONTRACT.md]\n");
    return 1;
}
