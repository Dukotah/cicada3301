/* ------------------------------------------------------------------ MT19937 (CPython 2.7 verbatim) */
typedef struct { uint32_t mt[624]; int idx; } MT;

static void mt_init_genrand(MT *r, uint32_t s) {
    r->mt[0] = s;
    for (int i = 1; i < 624; i++)
        r->mt[i] = 1812433253u * (r->mt[i-1] ^ (r->mt[i-1] >> 30)) + (uint32_t)i;
    r->idx = 624;
}

/* init_by_array([w]) -- runner.word_stream: [w] if w else [0] (identical at w=0) */
static void mt_init_word(MT *r, uint32_t w) {
    mt_init_genrand(r, 19650218u);
    uint32_t *mt = r->mt;
    int i = 1;                                  /* klen == 1, j stays 0 */
    for (int k = 624; k; k--) {
        mt[i] = (mt[i] ^ ((mt[i-1] ^ (mt[i-1] >> 30)) * 1664525u)) + w; /* + key[0] + j(=0) */
        i++;
        if (i >= 624) { mt[0] = mt[623]; i = 1; }
    }
    for (int k = 623; k; k--) {
        mt[i] = (mt[i] ^ ((mt[i-1] ^ (mt[i-1] >> 30)) * 1566083941u)) - (uint32_t)i;
        i++;
        if (i >= 624) { mt[0] = mt[623]; i = 1; }
    }
    mt[0] = 0x80000000u;
    r->idx = 624;
}

static inline uint32_t mt_u32(MT *r) {
    uint32_t y;
    if (r->idx >= 624) {
        uint32_t *mt = r->mt;
        for (int kk = 0; kk < 227; kk++) {
            y = (mt[kk] & 0x80000000u) | (mt[kk+1] & 0x7FFFFFFFu);
            mt[kk] = mt[kk+397] ^ (y >> 1) ^ ((y & 1u) ? 0x9908B0DFu : 0u);
        }
        for (int kk = 227; kk < 623; kk++) {
            y = (mt[kk] & 0x80000000u) | (mt[kk+1] & 0x7FFFFFFFu);
            mt[kk] = mt[kk-227] ^ (y >> 1) ^ ((y & 1u) ? 0x9908B0DFu : 0u);
        }
        y = (mt[623] & 0x80000000u) | (mt[0] & 0x7FFFFFFFu);
        mt[623] = mt[396] ^ (y >> 1) ^ ((y & 1u) ? 0x9908B0DFu : 0u);
        r->idx = 0;
    }
    y = r->mt[r->idx++];
    y ^= y >> 11;
    y ^= (y << 7)  & 0x9D2C5680u;
    y ^= (y << 15) & 0xEFC60000u;
    y ^= y >> 18;
    return y;
}

/* genrand_res53 -- bit-exact double (a*2^26+b are exact integer doubles; any FMA
 * contraction is value-identical, and we build with -ffp-contract=off anyway). */
static inline double mt_random(MT *r) {
    uint32_t a = mt_u32(r) >> 5, b = mt_u32(r) >> 6;
    return (a * 67108864.0 + b) * (1.0 / 9007199254740992.0);
}

/* ------------------------------------------------------------------ reducers (gen_py27.REDUCERS) */
enum { RED_RANDOM29, RED_GRB5_MOD, RED_GRB5_REJ, RED_SHUFFLE29 };

static int reducer_from_name(const char *s) {
    if (!strcmp(s, "random29"))  return RED_RANDOM29;
    if (!strcmp(s, "grb5_mod"))  return RED_GRB5_MOD;
    if (!strcmp(s, "grb5_rej"))  return RED_GRB5_REJ;
    if (!strcmp(s, "shuffle29")) return RED_SHUFFLE29;
    return -1;
}

static void reduce_stream(MT *r, int reducer, uint8_t *ks, int n) {
    switch (reducer) {
    case RED_RANDOM29:
        for (int i = 0; i < n; i++) ks[i] = (uint8_t)(int)(mt_random(r) * 29.0);
        break;
    case RED_GRB5_MOD:                      /* getrandbits(5) % 29 */
        for (int i = 0; i < n; i++) ks[i] = (uint8_t)((mt_u32(r) >> 27) % 29u);
        break;
    case RED_GRB5_REJ:                      /* getrandbits(5), reject 29..31 */
        for (int i = 0; i < n; ) {
            uint32_t v = mt_u32(r) >> 27;
            if (v < 29u) ks[i++] = (uint8_t)v;
        }
        break;
    case RED_SHUFFLE29: {                   /* repeated Fisher-Yates over range(29) */
        int got = 0;
        uint8_t pool[NRUNE];
        while (got < n) {
            for (int i = 0; i < NRUNE; i++) pool[i] = (uint8_t)i;
            for (int i = NRUNE - 1; i > 0; i--) {
                int j = (int)(mt_random(r) * (double)(i + 1));
                uint8_t t = pool[i]; pool[i] = pool[j]; pool[j] = t;
            }
            for (int i = 0; i < NRUNE && got < n; i++) ks[got++] = pool[i];
        }
        break; }
    }
}

