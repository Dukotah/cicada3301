"""Write RESULTS.md for lane S2 from results.json and control.json (no hand-typed numbers)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
r = json.load(open(os.path.join(HERE, "results.json")))
c = json.load(open(os.path.join(HERE, "control.json")))
L = []
A = L.append
A("# RESULTS — Round 44 lane S2: glibc `rand()` seeded by the clock, through the blind adjudicator")
A("")
A("_Run 2026-11-12 after `PREREG.md` (committed first, ec9b73c). Generated by `write_results.py` from `results.json`")
A("and `control.json`._")
A("")
A("## Verdict")
A("")
nflag = sum(len(v["flagged"]) for v in r["generators"].values())
if r["verdict"] == "NEGATIVE":
    A(f"**NEGATIVE, complete.** {r['keystreams_evaluated']:,} keystreams (two reductions x 90,562,816 seeds: every integer below "
      f"2^24 and every second from 2011-12-01 to 2014-04-03 UTC), four modes each. **None** reaches the full-page threshold. "
      f"Control: {r['control']}.")
elif r["verdict"].startswith("FLAGGED"):
    A(f"**FLAGGED-FOR-ORACLE: {nflag} pair(s) clear all three stages.** Not a solve; see the rows below. Control: {r['control']}.")
else:
    A(f"**{r['verdict']}.** Keystreams evaluated: {r['keystreams_evaluated']:,}. Control: {r['control']}.")
A("")
A("| reduction | seeds | reach stage 3 | flagged | largest IoC x 29 at L=262 (seed, mode) |")
A("|---|---|---|---|---|")
names = {"glibcmod": "`rand() % 29`", "glibcscale": "`floor(29 * rand() / 2^31)`"}
for g, v in r["generators"].items():
    b = v["best_rows"][0] if v["best_rows"] else None
    A(f"| {names[g]} | {v['seeds_evaluated']:,} | {v['stage3_records']:,} | {len(v['flagged'])} | "
      + (f"{b['ioc_x29_L262']:.3f} ({b['seed']}, {b['mode']})" if b else "n/a") + " |")
A("")
A("Threshold at L=262: 1.40. The weakest of lane S1's 432 calibration plants scored 1.614.")
if r.get("best_panel_pmax_among_top_rows") is not None:
    A(f"The 1,000 best rows were decoded along their best path at L=120 and adjudicated by panel-R36: largest panel pmax "
      f"{r['best_panel_pmax_among_top_rows']:.2f} (`sweep_rows_top.jsonl`, SWEEPROW/1).")
A("")
A("Both server timestamps recorded by Round 43 F5b (1389478032 and 1396427599) are inside the swept window.")
A("")
A("## Control")
A("")
A(f"{c['flagged']} of {c['of']} planted seeds flagged in their true mode, {c['other_seeds_flagged']} other seeds flagged across 16 "
  "windows of 2^18 seeds. Keystreams came from the system C library itself (a ten-line program calling `srand` / `rand`). "
  "Plants rotate both reductions, English letter-wise / English multigraph / Latin, as written / random relabelling / +7 "
  "constant / Beaufort, keyskip1 / skip_by_two / coin_from_key, both key signs.")
A("")
A("## What this covers, and what it does not")
A("")
A("1. **Key space:** glibc `srand(t)` for every t in [0, 2^24) and every second of 2011-12-01 .. 2014-04-03 UTC; two "
  "reductions; no draws before the first rune; stream starts at rune 0 of page 0.")
A("2. **Transition model:** as lane S1 (one or two draws per rejection, in-stream coin, both key signs, any combiner "
  "constant, Atbash and Beaufort).")
A("3. **Register:** none needed.")
A("")
A("Not covered: seeds outside the two ranges (`time ^ pid`, `time * pid`, microseconds, the rest of 2^32); other "
  "reductions; other C libraries (musl, BSD, MSVC `rand` differ); a warm-up; a start at another section head; a stalled "
  "key pointer; deletion or rewrite without a draw. The full 2^32 for both reductions is about ten core-hours with this "
  "kernel and is the natural next run.")
A("")
A("## Reproduce")
A("")
A("```bash")
A("python3 run_s2.py control && python3 run_s2.py sweep 4 && python3 run_s2.py finalize && python3 write_results.py")
A("```")
open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L[:12]))
