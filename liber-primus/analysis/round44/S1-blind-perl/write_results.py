"""Write RESULTS.md for lane S1 from results.json, control.json and calibration.json (no hand-typed numbers)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
r = json.load(open(os.path.join(HERE, "results.json")))
c = json.load(open(os.path.join(HERE, "control.json")))
cal = json.load(open(os.path.join(HERE, "calibration.json")))
t = r["thresholds"]
pairs = r["pairs_evaluated"]
s1 = sum(r["stage1_pass_by_mode"])
verdict = r["verdict"]
top = r["best_null_rows"]
lines = []
A = lines.append
A("# RESULTS — Round 44 lane S1: every Perl `rand` seed, through the blind adjudicator")
A("")
A("_Run 2026-11-12 after `PREREG.md` (committed first, 92e7368). Generated by `write_results.py` from")
A("`results.json`, `control.json` and `calibration.json`; no number below is typed by hand._")
A("")
A("## Verdict")
A("")
if verdict == "NEGATIVE":
    A(f"**NEGATIVE, complete.** All {r['seeds_evaluated']:,} seeds of Perl's `srand` were evaluated in four modes "
      f"({pairs:,} seed-mode pairs). **None** reaches the pre-registered full-page threshold. The control passed "
      f"({r['control']}).")
elif verdict.startswith("FLAGGED") and r.get("adjudication", {}).get("all_flags_noise_crossers"):
    ad = r["adjudication"]
    A(f"**No key found. All {r['seeds_evaluated']:,} seeds were evaluated in four modes ({pairs:,} seed-mode pairs), and no pair "
      f"comes near a planted key.** The largest full-page statistic is {r['max_ioc_x29_L262']:.3f}; the weakest of 432 calibration "
      f"plants scored {cal['plant_ioc_L262']['min']:.3f}. Control: {r['control']}.")
    A("")
    A(f"**By the letter of the pre-registration the lane is FLAGGED, weakly:** {ad['weak_flags']} pairs sit between 1.40 (the registered "
      f"threshold) and 1.433, and none reaches 1.50. The addendum to `PREREG.md`, written before any output was read, said a sweep of "
      f"this size should produce a few such values from wrong keys alone. Its decay rule marks {ad['weak_flags_null_consistent_by_prereg_decay_rule']} "
      f"of them null-consistent; the other {ad['weak_flags'] - ad['weak_flags_null_consistent_by_prereg_decay_rule']} were owed an oracle step. That step is "
      f"filed in `ORACLE-PENDING.md` with a recommendation of **NOISE-CROSSER for all {ad['weak_flags']}**, on four checks made after the "
      "flags were seen, each with a control:")
    A("")
    A(f"- **held-out page:** decoding page 1 from where page 0 ended, plants score {ad['heldout_page1']['plants_min']:.3f} or more; "
      f"every flag scores {ad['heldout_page1']['flags_max']:.3f} or less (mean {ad['heldout_page1']['flags_mean']:.3f}), a random key's level (`heldout_page1.py`);")
    A(f"- **back half of page 0:** plants {ad['back_half']['plants_min']:.3f} or more, flags {ad['back_half']['flags_max']:.3f} or less;")
    A(f"- **reading** (the decode solved as a simple substitution of English): plants come back as readable English at "
      f"{ad['substitution_reading']['plants_min']:.2f} or better, wrong keys {ad['substitution_reading']['wrong_keys_max']:.2f} or worse, flags "
      f"{ad['substitution_reading']['flags_max']:.2f} or worse (`adjudicate_flags.py`);")
    A("- **tail shape:** pairs at or above each level: " + ", ".join(f"{k}: {v:,}" for k, v in ad["tail_counts_S1"].items() if float(k) <= 1.44)
      + ". A smooth decay with no isolated point; lane S2 has the same curve at 1/24 the height.")
    A("")
    A("The owner's sign-off on those rows is the one thing outstanding. Filed in the ledger as negative with that note.")
elif verdict.startswith("FLAGGED"):
    A(f"**FLAGGED-FOR-ORACLE: {len(r['flagged'])} seed-mode pair(s) clear all three pre-registered stages.** This is not a "
      f"solve. The decodes are below and go to a human read per `HUMAN-ORACLE.md`. Control: {r['control']}.")
else:
    A(f"**{verdict}.** Seeds evaluated: {r['seeds_evaluated']:,} of 4,294,967,296 ({r['chunks_done']}/{r['of_chunks']} chunks). "
      f"Control: {r['control']}.")
A("")
A("| stage | L | threshold (IoC x 29) | pairs passing | rate |")
A("|---|---|---|---|---|")
A(f"| 1 | {t['L1']} | {29 * (t['T1'] - t['L1']) / (t['L1'] * (t['L1'] - 1)):.3f} | {s1:,} | {s1 / pairs:.4f} |")
A(f"| 2 | {t['L2']} | {29 * (t['T2'] - t['L2']) / (t['L2'] * (t['L2'] - 1)):.3f} | {r['stage3_records']:,} | {r['stage3_rate_per_pair']:.2e} |")
A(f"| 3 | {t['L3']} | {29 * (t['T3'] - t['L3']) / (t['L3'] * (t['L3'] - 1)):.3f} | {len(r['flagged']):,} | {len(r['flagged']) / pairs:.1e} |")
A("")
A(f"The largest full-page statistic of any seed is **{r['max_ioc_x29_L262']:.3f}** "
  f"(seed {top[0]['seed']}, {top[0]['mode']}); the threshold is 1.40 and the weakest of the 432 calibration plants scored "
  f"{cal['plant_ioc_L262']['min']:.3f}. The ten best rows:")
A("")
A("| seed | mode | IoC x 29 at L=120 | IoC x 29 at L=262 |")
A("|---|---|---|---|")
for x in top:
    A(f"| {x['seed']} | {x['mode']} | {x['ioc_x29_L120']:.3f} | {x['ioc_x29_L262']:.3f} |")
A("")
if r.get("flagged") and not r.get("adjudication", {}).get("all_flags_noise_crossers"):
    A("## Flagged pairs")
    A("")
    for f in r["flagged"]:
        A(f"- seed {f['seed']}, {f['mode']}: IoC x 29 = {f['ioc_x29_L64']:.3f} / {f['ioc_x29_L120']:.3f} / {f['ioc_x29_L262']:.3f} "
          f"at L = 64 / 120 / 262. Decode in Gematria order: `{f.get('decode_gematria_order', '')[:200]}`")
    A("")
A("## Control and power")
A("")
A(f"- **Through the sweep binary:** {c['flagged']} of {c['of']} planted Perl seeds flagged in their true mode, "
  f"{c['other_seeds_flagged']} other seeds flagged across 24 windows of 2^18 seeds. Keystreams came from the `perl` binary. "
  "Plants rotate English letter-wise / English multigraph / Latin; as written / random relabelling / +7 constant / "
  "Beaufort; keyskip1 / skip_by_two / coin_from_key; both key signs.")
p1 = cal["L1=64"]["plant_pass_at_T1"]
A(f"- **Calibration (432 plants, random keys):** stage-1 pass rate at the 3 % null threshold {p1:.3f} "
  f"(431 of 432 at the registered 6 % threshold); IoC x 29 at L=120: minimum {cal['plant_ioc_L120']['min']:.3f}, "
  f"1st percentile {cal['plant_ioc_L120']['p01']:.3f}; at L=262: minimum {cal['plant_ioc_L262']['min']:.3f}.")
if r.get("best_panel_pmax_among_top_rows") is not None:
    A(f"- **Re-read in the panel:** the 2,000 best rows were decoded along their best path at L=120 and adjudicated by "
      f"panel-R36; the largest panel pmax among them is {r['best_panel_pmax_among_top_rows']:.2f} "
      f"(`sweep_rows_top.jsonl`, SWEEPROW/1).")
A("")
A("## What this covers, and what it does not")
A("")
A("Read as: excluded within (key space) x (transition model), with **no register conditional**.")
A("")
A("1. **Key space:** every one of the 2^32 `srand` seeds, explicit or automatic; the idiom `int(rand(29))`; no draws "
  "consumed before the first rune; the stream starts at rune 0 of page 0.")
A("2. **Transition model:** one draw per rune; a rejection consumes one draw or two, with or without the in-stream coin; "
  "at most 8 / 12 / 24 rejections in the first 64 / 120 / 262 runes; both signs of the key. **Any constant in the "
  "combiner, Atbash and Beaufort are covered**, which no earlier sweep in this repository can say.")
A("3. **Register:** none. Any plaintext whose symbols have IoC x 29 of about 1.4 or more over the page, in any "
  "language, spelling or numbering of the symbols.")
A("")
A("Not covered: a warm-up (draws consumed before rune 0); a stream that starts at another section or page head; other "
  "reductions of `rand` (`rand()*29` rounded, `rand(28)+1`, a modulus of a larger draw); a key pointer that stalls (an F "
  "left in clear); rejection by deleting or rewriting the rune without a draw; separators that consume draws; Perl "
  "builds whose `rand` is not `drand48` (none known on Linux).")
A("")
A("Reopens if: any of the items above is given a reason; or a plaintext model with near-uniform symbol use is proposed.")
A("")
A("## Reproduce")
A("")
A("```bash")
A("python3 calibrate.py 2000000   # null on random keys + 432 plants      -> calibration.json")
A("python3 run_s1.py control      # 24 Perl-seed plants through the binary -> control.json")
A("python3 run_s1.py sweep 4      # all 2^32 seeds, resumable chunks")
A("python3 run_s1.py finalize     # merge, verdict, SWEEPROW store         -> results.json, hist.json")
A("python3 adjudicate_flags.py    # weak flags: tail shape, back half, reading -> flags_adjudication.json")
A("python3 heldout_page1.py       # weak flags: the held-out page          -> heldout_page1.json")
A("python3 write_results.py       # this file")
A("```")
open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines[:16]))
