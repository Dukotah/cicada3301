#!/usr/bin/env python3
"""Build the ARCHIVAL BUNDLE manifest (see ARCHIVAL-BUNDLE.md).

Enumerates the IRREPLACEABLE-external trees (primary material a clone does not
ship and a future solver cannot refetch if sources die), hashes every file that
is NOT tracked by git, and writes:

    handoff/archival-bundle.manifest.tsv   (path <TAB> bytes <TAB> sha256)

Run from the repo root:

    python3 liber-primus/handoff/build_archival_manifest.py

The manifest is the record; the tar line in ARCHIVAL-BUNDLE.md packs exactly
the paths in column 1. Hashes are measured, never typed (capsule rule).
"""

import hashlib
import os
import subprocess
import sys

# Repo-root-relative trees. Keep in sync with ARCHIVAL-BUNDLE.md section 2.
IRREPLACEABLE_TREES = [
    "liber-primus/data/relikd",
    "corpus/A-primary-artifacts",
    "liber-primus/analysis/round12/A1/pads",
    "liber-primus/analysis/round12/C2/texts",
    "liber-primus/analysis/armada_osint/artifacts",
    "liber-primus/analysis/armada_osint/onions_ibotpeaches",
    "liber-primus/analysis/anend_hunt/fetched",
    "liber-primus/analysis/round10/L6-archives/fetched",
    "liber-primus/analysis/round19/C3/l8/archives",
    "liber-primus/analysis/round43/F5-stored/fetched",
    "corpus/D-archives/captures",
    "corpus/G-forensics/raw",
]

SKIP_BASENAMES = {"__pycache__", ".pytest_cache", ".git"}


def sha256_file(path, bufsize=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            b = f.read(bufsize)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def main():
    root = subprocess.check_output(
        ["git", "rev-parse", "--show-toplevel"], text=True
    ).strip()
    os.chdir(root)
    tracked = set(
        subprocess.check_output(["git", "ls-files"], text=True).splitlines()
    )

    rows = []
    for tree in IRREPLACEABLE_TREES:
        if not os.path.isdir(tree):
            print(f"WARNING: tree missing on this machine: {tree}", file=sys.stderr)
            continue
        for dirpath, dirnames, filenames in os.walk(tree):
            dirnames[:] = [d for d in dirnames if d not in SKIP_BASENAMES]
            for fn in sorted(filenames):
                rel = os.path.join(dirpath, fn).replace(os.sep, "/")
                if rel in tracked:
                    continue  # ships with the clone already
                size = os.path.getsize(rel)
                rows.append((rel, size, sha256_file(rel)))

    rows.sort()
    out = os.path.join("liber-primus", "handoff", "archival-bundle.manifest.tsv")
    with open(out, "w") as f:
        f.write("# path\tbytes\tsha256  (generated by build_archival_manifest.py; measured, not typed)\n")
        for rel, size, digest in rows:
            f.write(f"{rel}\t{size}\t{digest}\n")

    total = sum(r[1] for r in rows)
    print(f"files: {len(rows)}")
    print(f"bytes: {total} ({total / 1e6:.1f} MB)")
    per = {}
    for rel, size, _ in rows:
        for tree in IRREPLACEABLE_TREES:
            if rel.startswith(tree + "/") or rel == tree:
                n, b = per.get(tree, (0, 0))
                per[tree] = (n + 1, b + size)
                break
    for tree in IRREPLACEABLE_TREES:
        n, b = per.get(tree, (0, 0))
        print(f"  {tree}: {n} files, {b / 1e6:.1f} MB")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
